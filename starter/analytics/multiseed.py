"""Run every scenario with several seeds and report each difference vs baseline with a 95 % interval.

    python analytics/multiseed.py run --days 180 --jobs 8     # data/seeds/<scenario>_seed<seed>/
    python analytics/multiseed.py report                      # docs/MULTISEED.md (generated: never edit it)

One run is one draw. Differences are paired by seed: the same seed gives both scenarios the same
customers, demand and deliveries (separate random streams in simulation.py), so what they share cancels
and the interval is about the decision. The interval is a t interval over the seeds' paired differences.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

import pandas as pd
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import config as C  # noqa: E402

SEEDS = (42, 7, 11, 23, 99)
SEED_DIR = os.path.join(ROOT, C.DATA_DIR, "seeds")
REPORT = os.path.join(ROOT, "docs", "MULTISEED.md")
KPIS = {                                   # column: (label, scale, unit)
    "on_time": ("On-time", 100, "pts"),
    "fill_rate": ("Fill rate", 100, "pts"),
    "wages": ("Wages / day", 1, "$"),
    "penalties": ("Penalties / day", 1, "$"),
    "profit": ("Profit / day", 1, "$"),
}


def run_all(days, seeds, scenarios, jobs, seed_dir=SEED_DIR):
    def one(sc_seed):
        sc, seed = sc_seed
        out = os.path.join(seed_dir, f"{sc}_seed{seed}")
        subprocess.run([sys.executable, os.path.join(ROOT, "main.py"), "--days", str(days), "--seed", str(seed),
                        "--scenario", sc, "--out", out], check=True, capture_output=True)
        return out
    pairs = [(sc, s) for sc in scenarios for s in seeds]
    with ThreadPoolExecutor(jobs) as ex:
        for out in ex.map(one, pairs):
            print(out)


def per_run(seed_dir=SEED_DIR):
    rows = []
    for name in sorted(os.listdir(seed_dir)):
        meta = os.path.join(seed_dir, name, "run.json")
        if not os.path.exists(meta):
            continue
        m = json.load(open(meta))
        k = pd.read_csv(os.path.join(seed_dir, name, "fact_daily_kpi.csv"))
        rows.append({"scenario": m["scenario"], "seed": m["seed"], **k[list(KPIS)].mean().to_dict()})
    return pd.DataFrame(rows)


def paired(df, scenario, kpi, base="baseline"):
    """Mean paired difference (scenario - base), its 95 % t interval and the number of seeds."""
    a = df[df.scenario == scenario].set_index("seed")[kpi]
    b = df[df.scenario == base].set_index("seed")[kpi]
    d = (a - b).dropna()
    n = len(d)
    if n < 2:
        return d.mean(), float("nan"), float("nan"), n
    half = stats.t.ppf(0.975, n - 1) * d.std(ddof=1) / n ** 0.5
    return d.mean(), d.mean() - half, d.mean() + half, n


def fmt(v, scale, unit):
    v *= scale
    return f"{v:+.1f} pts" if unit == "pts" else f"{'+' if v >= 0 else '−'}${abs(v):,.0f}"


def report(seed_dir=SEED_DIR, path=REPORT):
    df = per_run(seed_dir)
    lines = ["# Multi-seed comparison", "",
             "Generated by `python analytics/multiseed.py report`: never edit the numbers by hand. "
             f"Each scenario minus baseline, paired by seed, with a 95 % t interval over {df.seed.nunique()} seeds. "
             "An interval that contains 0 means the runs do not show a difference.", ""]
    for sc in [s for s in C.SCENARIOS if s != "baseline" and s in set(df.scenario)]:
        lines += [f"## {sc}", "", "| KPI | Difference | 95 % interval | Seeds |", "|---|---|---|---|"]
        for kpi, (label, scale, unit) in KPIS.items():
            m, lo, hi, n = paired(df, sc, kpi)
            lines.append(f"| {label} | **{fmt(m, scale, unit)}** | {fmt(lo, scale, unit)} to {fmt(hi, scale, unit)} | {n} |")
        lines.append("")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(path)
    return df


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["run", "report"])
    ap.add_argument("--days", type=int, default=180)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    a = ap.parse_args()
    if a.cmd == "run":
        run_all(a.days, SEEDS, list(C.SCENARIOS), a.jobs)
    else:
        report()
